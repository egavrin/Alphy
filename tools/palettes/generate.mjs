// Writes ToolPalettes.kt: the curated app palettes as Material 3 color schemes.
// Each palette is a Material "vibrant" dynamic scheme from one seed color, in light and dark variants.
// Usage: copy this file into an empty directory outside the repository, and run in that directory:
//   bun add @material/material-color-utilities@0.3.0
//   bun generate.mjs > <repo>/app/src/main/java/com/alpha/assistant/tools/ToolPalettes.kt
import {Hct, SchemeVibrant, TonalPalette, MaterialDynamicColors as M, argbFromHex} from '@material/material-color-utilities';

const seeds = {
  blue: '#2F6FED', teal: '#00897B', green: '#3C8D40', amber: '#E8A317', orange: '#F4511E',
  red: '#E53935', pink: '#D81B60', purple: '#8E24AA', indigo: '#3949AB', brown: '#8D6E63',
};
// Status colors stay the same in every palette, so "success" never takes the hue of a red palette.
const status = {success: '#2E7D32', warning: '#F9A825'};
const roles = ['primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer', 'inversePrimary',
  'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'background', 'onBackground', 'surface', 'onSurface', 'surfaceVariant', 'onSurfaceVariant', 'surfaceTint',
  'inverseSurface', 'inverseOnSurface', 'error', 'onError', 'errorContainer', 'onErrorContainer',
  'outline', 'outlineVariant', 'scrim', 'surfaceBright', 'surfaceContainer', 'surfaceContainerHigh',
  'surfaceContainerHighest', 'surfaceContainerLow', 'surfaceContainerLowest', 'surfaceDim',
  'primaryFixed', 'primaryFixedDim', 'onPrimaryFixed', 'onPrimaryFixedVariant',
  'secondaryFixed', 'secondaryFixedDim', 'onSecondaryFixed', 'onSecondaryFixedVariant',
  'tertiaryFixed', 'tertiaryFixedDim', 'onTertiaryFixed', 'onTertiaryFixedVariant'];
const hex = (argb) => '0x' + (argb >>> 0).toString(16).toUpperCase().padStart(8, '0');
const values = (seed, dark) => {
  const scheme = new SchemeVibrant(Hct.fromInt(argbFromHex(seed)), dark, 0);
  return roles.map((role) => hex(M[role].getArgb(scheme)));
};
// ink, background, foreground, the same order as ToolRole.
const statusTones = (seed, dark) => {
  const palette = TonalPalette.fromInt(argbFromHex(seed));
  return (dark ? [80, 30, 90] : [40, 90, 10]).map((tone) => hex(palette.tone(tone)));
};
const rows = (list) => list.map((value, index) => (index % 6 === 0 ? '\n            ' : ' ') + value).join(',');
const out = [];
out.push(`// Generated by tools/palettes/generate.mjs. Do not edit by hand.
package com.alpha.assistant.tools

import androidx.compose.material3.ColorScheme
import androidx.compose.ui.graphics.Color

/** Curated app palettes: Material 3 vibrant schemes from one seed color each, in light and dark variants. */
internal object ToolPalettes {
    /** The shell's own gray colors. */
    const val GRAPHITE = "graphite"
    val names: List<String> = listOf(GRAPHITE, ${Object.keys(seeds).map((n) => `"${n}"`).join(', ')})

    /** The scheme for a palette name, or null for graphite, which keeps the shell colors. */
    fun scheme(name: String, dark: Boolean): ColorScheme? = schemes[name]?.let { build(if (dark) it.second else it.first) }

    /** ink, background, and foreground of a status tone. */
    fun status(tone: String, dark: Boolean): Triple<Color, Color, Color>? =
        statuses[tone]?.let { (if (dark) it.second else it.first).let { c -> Triple(Color(c[0]), Color(c[1]), Color(c[2])) } }

    private fun build(c: LongArray) = ColorScheme(
${roles.map((r, i) => `        ${r} = Color(c[${i}]),`).join('\n')}
    )

    private val schemes: Map<String, Pair<LongArray, LongArray>> = mapOf(`);
for (const [name, seed] of Object.entries(seeds)) {
  out.push(`        "${name}" to Pair(longArrayOf(${rows(values(seed, false))}),\n        longArrayOf(${rows(values(seed, true))})),`);
}
out.push(`    )

    private val statuses: Map<String, Pair<LongArray, LongArray>> = mapOf(`);
for (const [name, seed] of Object.entries(status)) {
  out.push(`        "${name}" to Pair(longArrayOf(${statusTones(seed, false).join(', ')}), longArrayOf(${statusTones(seed, true).join(', ')})),`);
}
out.push(`    )
}
`);
console.log(out.join('\n'));
